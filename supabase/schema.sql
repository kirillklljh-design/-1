-- Run once in the SQL Editor of a NEW Supabase project.
-- Owner access is assigned separately after creating a user in Authentication.
begin;
create table public.site_owners (
  user_id uuid primary key references auth.users(id) on delete cascade
);
alter table public.site_owners enable row level security;
revoke all on public.site_owners from anon, authenticated;

create function public.is_site_owner() returns boolean
language sql stable security definer set search_path = ''
as $$ select exists(select 1 from public.site_owners where user_id = (select auth.uid())) $$;
revoke all on function public.is_site_owner() from public;
grant execute on function public.is_site_owner() to anon, authenticated;

create table public.machines (
  id text primary key check (id ~ '^[A-Za-z0-9_-]{1,80}$'),
  name text not null check (length(trim(name)) between 1 and 100),
  description text not null check (length(trim(description)) between 1 and 500),
  rate numeric(12,2) not null check (rate > 0 and rate <= 100000000),
  min_hours integer not null check (min_hours >= 1),
  image_key text check (image_key in ('reference-mini','reference-excavator','reference-loader','reference-truck') or image_key ~ '^[a-f0-9-]+\.(jpg|png|webp)$'),
  visible boolean not null default true,
  sort_order bigint generated by default as identity (start with 100)
);
alter table public.machines enable row level security;
revoke all on public.machines from anon, authenticated;
grant select on public.machines to anon, authenticated;
grant insert, update, delete on public.machines to authenticated;
grant usage on sequence public.machines_sort_order_seq to authenticated;
create policy "Visible machines or owner" on public.machines for select to anon, authenticated
using (visible or (select public.is_site_owner()));
create policy "Owner creates machines" on public.machines for insert to authenticated
with check ((select public.is_site_owner()));
create policy "Owner updates machines" on public.machines for update to authenticated
using ((select public.is_site_owner())) with check ((select public.is_site_owner()));
create policy "Owner deletes machines" on public.machines for delete to authenticated
using ((select public.is_site_owner()));

insert into storage.buckets (id,name,public,file_size_limit,allowed_mime_types)
values ('machine-photos','machine-photos',true,5242880,array['image/jpeg','image/png','image/webp']);
create policy "Owner lists photos" on storage.objects for select to authenticated
using (bucket_id='machine-photos' and (select public.is_site_owner()));
create policy "Owner uploads photos" on storage.objects for insert to authenticated
with check (bucket_id='machine-photos' and (select public.is_site_owner()));

-- One-time initial content. Never execute on every request: deleted machines must stay deleted.
